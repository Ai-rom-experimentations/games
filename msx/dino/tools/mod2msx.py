#!/usr/bin/env python3
"""tools/mod2msx.py - a ProTracker module into an AY-3-8910 script.

    python3 tools/mod2msx.py tools/dino.mod > music.asm

Only what a three channel PSG can do is taken from the module: one voice for
the lead (channel 0 of the module) and one for the bass (channel 1).  Channel
C of the PSG is left alone so the game's own sounds never cut the tune.

Each voice becomes a list of three byte events - note, length in frames,
volume - with note 0 for a rest, and 0xFF to jump back to the start of the
track.  dino.asm's track_tick() plays them.
"""
import struct
import sys

MOD_PERIODS = [
    856, 808, 762, 720, 678, 640, 604, 570, 538, 508, 480, 453,
    428, 404, 381, 360, 339, 320, 302, 285, 269, 254, 240, 226,
    214, 202, 190, 180, 170, 160, 151, 143, 135, 127, 120, 113,
    107, 101, 95, 90, 85, 80, 76, 71, 67, 64, 60, 57,
    54, 51, 48, 45, 43, 40, 38, 36, 34, 32, 30, 28,
]
FRAMES_PER_ROW = 6                    # 125 BPM, six ticks a row, 50 Hz


def psg_period(mod_note):
    """The AY counts 111860/f from the clock, so 440 Hz is 254."""
    # period 856 is C-1 at 32.703 Hz and every entry is a semitone up, so the
    # frequency of note n is simply 32.703 * 2^(n/12)
    hz = 32.703 * (2 ** (mod_note / 12.0))
    return max(1, min(4095, int(round(111860.0 / hz))))


def parse(path):
    d = open(path, "rb").read()
    if d[1080:1084] != b"M.K.":
        raise SystemExit("not a 4 channel M.K. module")
    songlen = d[950]
    order = list(d[952:952 + 128])[:songlen]
    samples = []
    for i in range(31):
        base = 20 + i * 30
        length = struct.unpack(">H", d[base + 22:base + 24])[0] * 2
        vol = d[base + 25]
        samples.append((length, vol))
    npat = max(order) + 1
    pats = []
    pos = 1084
    for p in range(npat):
        rows = []
        for r in range(64):
            cells = []
            for ch in range(4):
                b = d[pos:pos + 4]
                pos += 4
                period = ((b[0] & 0x0F) << 8) | b[1]
                ins = (b[0] & 0xF0) | (b[2] >> 4)
                cells.append((period, ins))
            rows.append(cells)
        pats.append(rows)
    return order, pats, samples


def voice(order, pats, samples, ch):
    """The note events of one module channel, rows merged into holds."""
    events = []
    for pat in order:
        for row in pats[pat]:
            period, ins = row[ch]
            if period == 0:
                events.append(None)          # hold what is playing
                continue
            note = min(range(len(MOD_PERIODS)),
                       key=lambda i: abs(MOD_PERIODS[i] - period))
            vol = 0
            if 1 <= ins <= len(samples):
                vol = int(round(samples[ins - 1][1] * 15 / 64.0))
            events.append((note, vol))
    out = []
    for e in events:
        if e is None:
            if out:
                out[-1][1] += 1
            continue
        out.append([e[0], 1, e[1]])
    for e in out:                            # a row is FRAMES_PER_ROW frames
        e[1] *= FRAMES_PER_ROW
    return out


def emit(events):
    lines = []
    for note, length, vol in events:
        while length > 0:
            chunk = min(length, 255)
            lines.append("        defb %d, %d, %d" % (note + 1, chunk, vol))
            length -= chunk
    lines.append("        defb 0xff")           # back to the top
    return lines


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "tools/dino.mod"
    order, pats, samples = parse(path)
    print("; generated by tools/mod2msx.py from %s - do not edit" % path)
    print("music_data:")
    print("        defw track_a, track_b")
    print("track_a:                                ; the lead")
    for line in emit(voice(order, pats, samples, 0)):
        print(line)
    print("track_b:                                ; the bass")
    for line in emit(voice(order, pats, samples, 1)):
        print(line)
    print("; note numbers are C-1 upwards, one word of period each")
    print("note_table:")
    for n in range(0, 96, 8):
        vals = []
        for i in range(n, min(n + 8, 96)):
            vals.append("0x%04X" % psg_period(i) if i < len(MOD_PERIODS) else "0")
        print("        defw " + ", ".join(vals))


if __name__ == "__main__":
    main()
